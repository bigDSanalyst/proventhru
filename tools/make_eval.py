"""Generate an eval set: true equations and inequalities over nat and list nat.

    python tools/make_eval.py --out examples/eval_test.txt --n 120 --seed 1

How the set is made, so it can be regenerated and audited:

1. Enumerate. Terms over the signature below (stdlib functions only), by
   size, QuickSpec style: each term is evaluated in Python on a fixed vector
   of random inputs, terms with the same values form a class, and only each
   class's smallest member is used to build bigger terms. Two members of a
   class give a candidate equation; two classes whose values are ordered on
   every input give a candidate inequality.
2. Test. Each candidate is re-tested on 2,000 fresh random inputs plus edge
   cases (empty lists, zeros). A candidate that fails any is dropped. That a
   statement holds on 2,000 inputs does not make it true; the gate's bounded
   refutation and the kernel at the end are the checks that count.
3. Shape. Kept only if it mentions a list variable (pure arithmetic is
   lia's), both sides are not variables or constants alone, and its size is
   in [--min-size, --max-size].
   No list subterm without a variable in it (skipn n [] = []: Coq cannot
   infer the type of [] there, and the law is about the constant).
   And not f(a, x) against f(a, y), which is an instance of a smaller law
   about x and y; and an inequality must be tight (equal on some input), so
   neither side is slack by a constant.
4. Sample. --n candidates by seeded random choice, spread over the head
   symbol of the left side so one function does not dominate. Step 2's
   testing happens here, on each sampled candidate in turn.
5. Gate (tools/gate_eval.py, separately). Only statements the gate leaves
   open stay: ill-formed, refuted, vacuous, trivial and already-in-library
   statements are dropped.

Difficulty is controlled here, by the generator's parameters, and never by
dropping individual statements because a baseline proved them: selecting
on a baseline's results would bias the comparison against that baseline.

--rename writes the same statements with the bound variables renamed
(l1 -> xs, l2 -> ys, n -> k, m -> j): Coq's Search returns the same lemmas,
so a drop in proof rate measures memorisation of surface forms, nothing else.
"""
import argparse
import os
import random
import sys
from collections import defaultdict

sys.path.insert(0, os.path.join(os.path.dirname(__file__), ".."))
from proventhru.conjecture import (  # noqa: E402
    EDGE, RENAME, canonical_names, candidates, enumerate_classes, holds, random_env, statement)


def main(argv=None):
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", required=True)
    ap.add_argument("--n", type=int, default=120)
    ap.add_argument("--seed", type=int, default=1)
    ap.add_argument("--max-term", type=int, default=5, help="largest term size enumerated")
    ap.add_argument("--min-size", type=int, default=5, help="smallest statement (both sides)")
    ap.add_argument("--max-size", type=int, default=9)
    ap.add_argument("--rename", default=None, help="also write the variable-renamed copy here")
    a = ap.parse_args(argv)

    rng = random.Random(a.seed)
    envs = EDGE + [random_env(rng) for _ in range(40)]
    check = EDGE + [random_env(rng) for _ in range(2000)]
    classes = enumerate_classes(a.max_term, envs)
    cands = candidates(classes, a.min_size, a.max_size)
    seen, by_head = set(), defaultdict(list)
    for c in cands:
        names = canonical_names(c[0], c[1])
        s = statement(*c, names)
        if s not in seen:
            seen.add(s)
            by_head[(c[2], c[0].head())].append(c + (names,))
    for h in sorted(by_head):
        rng.shuffle(by_head[h])
    picked, failed, heads = [], 0, sorted(by_head)
    while len(picked) < a.n and any(by_head.values()):
        for h in heads:
            while by_head[h] and len(picked) < a.n:
                c = by_head[h].pop()
                if holds(c[0], c[1], c[2], check):
                    picked.append(c)
                    break
                failed += 1
    header = (f"# Generated by tools/make_eval.py --n {a.n} --seed {a.seed} --max-term "
              f"{a.max_term} --min-size {a.min_size} --max-size {a.max_size}\n"
              f"# {len(seen)} candidates; {len(picked)} sampled that passed 2,000 random"
              f" tests ({failed} sampled failed).\n"
              "# preamble: Require Import Arith Lia List. Import ListNotations.\n")
    with open(a.out, "w") as fh:
        fh.write(header + "".join(statement(*c) + "\n" for c in picked))  # c[3]: names
    if a.rename:
        with open(a.rename, "w") as fh:
            fh.write(header.replace("sampled.", "sampled; variables renamed")
                     + "".join(statement(*c[:3], {v: RENAME[w] for v, w in c[3].items()}) + "\n"
                       for c in picked))
    print(f"{len(classes)} classes, {len(seen)} candidates, {failed} failed the tests, "
          f"{len(picked)} written to {a.out}")


if __name__ == "__main__":
    main()
