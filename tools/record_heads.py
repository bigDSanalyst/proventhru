"""Pin run records' heads in a committed file.

    python tools/record_heads.py RUNS_ROOT [--sums SHA256SUMS] > results/records-manifest.md

A hash chain shows only that a record agrees with itself; the head (size and
hash of the last entry) committed here pins it from outside, so a record
restored from an archive can be checked against this file with
`proventhru verify`. With --sums, the archives' own sha256 sums are listed
too, so the archives are pinned as well."""
import argparse
import glob
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(__file__), ".."))
from proventhru import record as rec  # noqa: E402


def main(argv=None):
    ap = argparse.ArgumentParser()
    ap.add_argument("root")
    ap.add_argument("--sums", default=None, help="a sha256sum file of the run archives")
    ap.add_argument("--date", required=True)
    ap.add_argument("--exclude", nargs="*", default=[], help="top-level directories to leave out")
    a = ap.parse_args(argv)
    files = sorted(f for f in glob.glob(os.path.join(a.root, "**", "records.jsonl"), recursive=True)
                   if os.path.relpath(f, a.root).split(os.sep)[0] not in a.exclude)
    print("# Run records: heads and archives\n")
    print(f"Generated by `tools/record_heads.py` on {a.date} from the run records under "
          f"`{a.root}`. The records themselves are not in the repository: they're in xz "
          "archives, one per run directory, held by the project owner.\n")
    print("A record restored from an archive is checked with `proventhru verify RECORD`, "
          "whose size and head must equal its row here. A record that doesn't verify, "
          "or whose head differs, isn't the record the results were computed from.\n")
    print("| record | entries | episodes | head | verifies |")
    print("|---|---|---|---|---|")
    for f in files:
        entries = rec.load(f)
        size, head = rec.head(entries)
        ok = "yes" if not rec.verify(entries) else "**no**"
        eps = sum(e.get("kind") == "episode" for e in entries)
        print(f"| `{os.path.relpath(f, a.root)}` | {size} | {eps} | `{head}` | {ok} |")
    if a.sums:
        print("\n## Archives\n")
        print("`sha256sum -c` against these lines checks the archives themselves.\n")
        print("```")
        with open(a.sums) as fh:
            print(fh.read().rstrip())
        print("```")


if __name__ == "__main__":
    main()
